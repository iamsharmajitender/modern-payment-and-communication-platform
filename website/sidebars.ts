import fs from 'node:fs';
import path from 'node:path';
import type {SidebarsConfig} from '@docusaurus/plugin-content-docs';

// Each folder under the repo-level docs/ is a topic. A topic's pages live in
// <topic>/docs/ when that folder exists, otherwise directly in <topic>/.
// The label and order come from <topic>/_category_.json. Topics with no
// Markdown pages yet are skipped, because Docusaurus rejects empty categories.
const docsRoot = path.resolve(__dirname, '../docs');

type TopicMeta = {label?: string; position?: number};

function readMeta(topic: string): TopicMeta {
  const file = path.join(docsRoot, topic, '_category_.json');
  return fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : {};
}

function hasPages(dir: string): boolean {
  return fs
    .readdirSync(dir, {withFileTypes: true})
    .some((entry) =>
      entry.isDirectory()
        ? hasPages(path.join(dir, entry.name))
        : /\.mdx?$/.test(entry.name),
    );
}

function toLabel(slug: string): string {
  const words = slug.replace(/-/g, ' ');
  return words.charAt(0).toUpperCase() + words.slice(1);
}

const topics = fs
  .readdirSync(docsRoot, {withFileTypes: true})
  .filter((entry) => entry.isDirectory() && hasPages(path.join(docsRoot, entry.name)))
  .map((entry) => ({slug: entry.name, meta: readMeta(entry.name)}))
  .sort(
    (a, b) =>
      (a.meta.position ?? Number.MAX_SAFE_INTEGER) -
        (b.meta.position ?? Number.MAX_SAFE_INTEGER) ||
      a.slug.localeCompare(b.slug),
  );

const sidebars: SidebarsConfig = {
  docs: topics.map(({slug, meta}) => {
    const nested = path.join(docsRoot, slug, 'docs');
    return {
      type: 'category' as const,
      label: meta.label ?? toLabel(slug),
      collapsed: false,
      items: [
        {
          type: 'autogenerated',
          dirName: fs.existsSync(nested) ? `${slug}/docs` : slug,
        },
      ],
    };
  }),
};

export default sidebars;
